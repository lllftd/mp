def format_bytes(bytes_size: int) -> str:
    """
    格式化字节大小
    
    Args:
        bytes_size: 字节数
        
    Returns:
        格式化后的字符串（如 "1.23 GB"）
    """
    for unit in ['B', 'KB', 'MB', 'GB', 'TB']:
        if bytes_size < 1024.0:
            return f"{bytes_size:.2f} {unit}"
        bytes_size /= 1024.0
    return f"{bytes_size:.2f} PB"


